# Shared render configuration for warehouse documentation.
#
# This support file is the one place where render paths and document ordering
# are defined. render.R and the master document both source it, so a folder move
# or version update should not require edits in several files.

find_render_config_file <- function() {
  for (frame in rev(sys.frames())) {
    if (!is.null(frame$ofile) && basename(frame$ofile) == "render_config.R") {
      return(normalizePath(frame$ofile, mustWork = TRUE))
    }
  }

  support_path <- file.path("render_support", "render_config.R")
  if (file.exists(support_path)) {
    return(normalizePath(support_path, mustWork = TRUE))
  }

  if (file.exists("render_config.R")) {
    return(normalizePath("render_config.R", mustWork = TRUE))
  }

  stop("Could not locate render_config.R.", call. = FALSE)
}

render_config_file <- find_render_config_file()
render_config_dir <- dirname(render_config_file)
doc_root <- if (basename(render_config_dir) == "render_support") {
  dirname(render_config_dir)
} else {
  render_config_dir
}
