sections_dir <- file.path(doc_root, "sections")
outputs_dir <- file.path(doc_root, "outputs")
# Standalone section renders go directly into outputs/. The source Rmd files
# stay in sections/, while generated PDFs stay in the generated-output folder.
section_outputs_dir <- outputs_dir

