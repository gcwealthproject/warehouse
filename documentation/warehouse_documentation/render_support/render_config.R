path_from_root <- function(...) {
  file.path(doc_root, ...)
}

render_path <- function(x, mustWork = FALSE) {
  normalized <- normalizePath(x, winslash = "/", mustWork = mustWork)
  gsub("\\", "/", normalized, fixed = TRUE)
}

master_child_paths <- function() {
  file.path(sections_dir, master_child_files)
}

required_child_files <- function() {
  c(
    file.path("sections", master_rmd_file),
    file.path("sections", "author.Rmd"),
    file.path("sections", master_child_files),
    file.path("sections", "fragments", fragment_files)
  )
}

label_from_section_file <- function(file) {
  override <- unname(section_label_overrides[file])
  if (!is.na(override)) {
    return(override)
  }

  name <- tools::file_path_sans_ext(file)
  is_appendix <- startsWith(name, "a_")
  name <- sub("^a_", "", name)
  name <- sub("^apdx_", "", name)
  label <- tools::toTitleCase(gsub("_", " ", name))
  if (is_appendix) {
    label <- paste("Appendix:", label)
  }
  label
}

ordered_section_files <- function() {
  # Preview choices are discovered automatically from sections/*.Rmd. New
  # topical sections appear before author/proj/gral; files beginning with a_
  # appear at the end as appendices.
  files <- list.files(sections_dir, pattern = "\\.Rmd$", full.names = FALSE)
  files <- files[!file.info(file.path(sections_dir, files))$isdir]
  files <- files[!startsWith(files, "_")]

  non_appendix <- files[!startsWith(files, "a_")]
  master_main <- master_child_files[
    master_child_files %in% non_appendix &
      !master_child_files %in% front_section_files
  ]
  discovered_main <- sort(setdiff(non_appendix, c(front_section_files, master_main)))
  main_sections <- c(master_main, discovered_main)
  front_sections <- front_section_files[front_section_files %in% files]
  appendix_files <- files[startsWith(files, "a_")]
  master_appendices <- master_child_files[master_child_files %in% appendix_files]
  discovered_appendices <- sort(setdiff(appendix_files, master_appendices))
  appendices <- c(master_appendices, discovered_appendices)

  c(main_sections, front_sections, appendices)
}

section_targets <- function() {
  files <- ordered_section_files()
  data.frame(
    index = seq_along(files),
    key = tools::file_path_sans_ext(files),
    label = vapply(files, label_from_section_file, character(1)),
    file = files,
    path = file.path(sections_dir, files),
    output_file = paste0(tools::file_path_sans_ext(files), ".pdf"),
    stringsAsFactors = FALSE
  )
}
